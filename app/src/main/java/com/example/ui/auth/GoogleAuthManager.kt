package com.example.ui.auth

import android.app.Activity
import android.content.Context
import android.content.ContextWrapper
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.Credential
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.ClearCredentialException
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential.Companion.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
import com.google.firebase.Firebase
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch
import kotlinx.coroutines.tasks.await

sealed interface AuthResult {
    data class Success(val user: FirebaseUser) : AuthResult
    object Cancelled : AuthResult
    data class Error(val message: String) : AuthResult
}

data class AuthUiState(
    val currentUser: FirebaseUser? = null,
    val isAutoSigningIn: Boolean = false,
    val isInteractiveSigningIn: Boolean = false,
    val errorMessage: String? = null
) {
    val isAuthenticated: Boolean get() = currentUser != null
    val isLoading: Boolean get() = isAutoSigningIn || isInteractiveSigningIn
}

/**
 * Handles Google Sign-In via Jetpack Credential Manager and Firebase Authentication.
 *
 * - Silent auto-sign-in uses [GetGoogleIdOption] in its own single-option [GetCredentialRequest].
 * - Interactive button sign-in uses [GetSignInWithGoogleOption] in its own single-option [GetCredentialRequest].
 * - Never combines both options in the same request to keep the Credential Manager sheet responsive on API 36.
 */
object GoogleAuthManager {
    private const val TAG = "Auth"

    private val _authUiState = MutableStateFlow(
        AuthUiState(
            currentUser = try {
                Firebase.auth.currentUser
            } catch (_: Exception) {
                null
            }
        )
    )
    val authUiState: StateFlow<AuthUiState> = _authUiState.asStateFlow()

    fun clearError() {
        _authUiState.update { it.copy(errorMessage = null) }
    }

    /**
     * Unwraps a [Context] to find the hosting [Activity] if available so Credential Manager
     * can anchor its bottom sheet UI properly.
     */
    fun Context.findActivity(): Activity? {
        var current: Context? = this
        while (current is ContextWrapper) {
            if (current is Activity) return current
            current = current.baseContext
        }
        return null
    }

    /**
     * Resolves `default_web_client_id` generated by the Google Services Gradle plugin,
     * falling back to `fallback_web_client_id` if `google-services.json` is not present.
     */
    fun resolveWebClientId(context: Context): String? {
        return try {
            val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
            if (resId != 0) {
                context.getString(resId).takeIf { it.isNotBlank() }
            } else {
                val fallbackId = context.resources.getIdentifier("fallback_web_client_id", "string", context.packageName)
                if (fallbackId != 0) {
                    context.getString(fallbackId).takeIf { it.isNotBlank() }
                } else {
                    null
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Unable to resolve default_web_client_id from resources", e)
            null
        }
    }

    /**
     * Builds a single-option [GetCredentialRequest] using [GetGoogleIdOption] for silent auto-sign-in.
     */
    fun buildSilentAutoSignInRequest(webClientId: String): GetCredentialRequest {
        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(webClientId)
            .setAutoSelectEnabled(true)
            .build()

        return GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()
    }

    /**
     * Builds a single-option [GetCredentialRequest] using [GetSignInWithGoogleOption] for interactive sign-in.
     */
    fun buildInteractiveSignInRequest(webClientId: String): GetCredentialRequest {
        val signInWithGoogleOption = GetSignInWithGoogleOption.Builder(
            serverClientId = webClientId
        ).build()

        return GetCredentialRequest.Builder()
            .addCredentialOption(signInWithGoogleOption)
            .build()
    }

    fun observeAuthState(): Flow<FirebaseUser?> = callbackFlow {
        val auth = try {
            Firebase.auth
        } catch (_: Exception) {
            trySend(null)
            close()
            return@callbackFlow
        }
        val listener = FirebaseAuth.AuthStateListener { firebaseAuth ->
            val user = firebaseAuth.currentUser
            _authUiState.update { state ->
                state.copy(
                    currentUser = user,
                    errorMessage = if (user != null) null else state.errorMessage
                )
            }
            trySend(user)
        }
        auth.addAuthStateListener(listener)
        awaitClose { auth.removeAuthStateListener(listener) }
    }

    /**
     * Silent Auto-Sign-In on app startup using [GetGoogleIdOption].
     * Falls back cleanly to [AuthResult.Cancelled] when no authorized credential is available
     * so the interactive "Sign in with Google" button is displayed.
     */
    suspend fun attemptAutoSignIn(
        activityContext: Context,
        credentialManager: CredentialManager = CredentialManager.create(activityContext),
        firebaseIdTokenExchanger: suspend (String) -> AuthResult = ::exchangeGoogleIdTokenWithFirebase
    ): AuthResult {
        val currentUser = try {
            Firebase.auth.currentUser
        } catch (_: Exception) {
            null
        }
        if (currentUser != null) {
            _authUiState.update {
                it.copy(currentUser = currentUser, isAutoSigningIn = false, errorMessage = null)
            }
            return AuthResult.Success(currentUser)
        }

        val webClientId = resolveWebClientId(activityContext)
        if (webClientId == null) {
            _authUiState.update { it.copy(isAutoSigningIn = false) }
            return AuthResult.Cancelled
        }

        _authUiState.update { it.copy(isAutoSigningIn = true, errorMessage = null) }
        val request = buildSilentAutoSignInRequest(webClientId)
        val requestContext = activityContext.findActivity() ?: activityContext

        return try {
            val result = credentialManager.getCredential(
                request = request,
                context = requestContext
            )
            val authResult = firebaseSignInWithCredential(result.credential, firebaseIdTokenExchanger)
            _authUiState.update { state ->
                when (authResult) {
                    is AuthResult.Success -> state.copy(
                        currentUser = authResult.user,
                        isAutoSigningIn = false,
                        errorMessage = null
                    )
                    else -> state.copy(isAutoSigningIn = false)
                }
            }
            authResult
        } catch (e: NoCredentialException) {
            Log.d(TAG, "No authorized Google credential for silent auto-sign-in: ${e.message}")
            _authUiState.update { it.copy(isAutoSigningIn = false) }
            AuthResult.Cancelled
        } catch (e: GetCredentialCancellationException) {
            Log.w(TAG, "Google Sign-In cancelled or dismissed: ${e.message}", e)
            _authUiState.update { it.copy(isAutoSigningIn = false) }
            AuthResult.Cancelled
        } catch (e: GetCredentialException) {
            Log.d(TAG, "Silent auto-sign-in not available (${e.type}): ${e.message}")
            _authUiState.update { it.copy(isAutoSigningIn = false) }
            AuthResult.Cancelled
        } catch (e: Exception) {
            Log.w(TAG, "Silent auto-sign-in failed", e)
            _authUiState.update { it.copy(isAutoSigningIn = false) }
            AuthResult.Cancelled
        }
    }

    /**
     * Callback-based helper for silent auto-sign-in matching the Credential Manager lifecycle pattern.
     */
    fun attemptAutoSignIn(
        context: Context,
        credentialManager: CredentialManager = CredentialManager.create(context),
        onAuthSuccess: () -> Unit,
        onUnauthenticated: () -> Unit,
        scope: CoroutineScope
    ) {
        scope.launch {
            when (attemptAutoSignIn(context, credentialManager)) {
                is AuthResult.Success -> onAuthSuccess()
                else -> onUnauthenticated()
            }
        }
    }

    /**
     * Interactive Google Sign-In triggered by the "Sign in with Google" button using [GetSignInWithGoogleOption].
     */
    suspend fun onGoogleSignInClicked(
        activityContext: Context,
        credentialManager: CredentialManager = CredentialManager.create(activityContext),
        firebaseIdTokenExchanger: suspend (String) -> AuthResult = ::exchangeGoogleIdTokenWithFirebase
    ): AuthResult {
        val webClientId = resolveWebClientId(activityContext)
        if (webClientId == null) {
            val msg = "Google Sign-In configuration missing: default_web_client_id not found"
            _authUiState.update { it.copy(isInteractiveSigningIn = false, errorMessage = msg) }
            return AuthResult.Error(msg)
        }

        _authUiState.update { it.copy(isInteractiveSigningIn = true, errorMessage = null) }
        val request = buildInteractiveSignInRequest(webClientId)
        val requestContext = activityContext.findActivity() ?: activityContext

        return try {
            val result = credentialManager.getCredential(
                request = request,
                context = requestContext
            )
            val authResult = firebaseSignInWithCredential(result.credential, firebaseIdTokenExchanger)
            _authUiState.update { state ->
                when (authResult) {
                    is AuthResult.Success -> state.copy(
                        currentUser = authResult.user,
                        isInteractiveSigningIn = false,
                        errorMessage = null
                    )
                    is AuthResult.Cancelled -> state.copy(isInteractiveSigningIn = false)
                    is AuthResult.Error -> state.copy(
                        isInteractiveSigningIn = false,
                        errorMessage = authResult.message
                    )
                }
            }
            authResult
        } catch (e: GetCredentialCancellationException) {
            Log.w(TAG, "Google Sign-In cancelled or dismissed: ${e.message}", e)
            _authUiState.update { it.copy(isInteractiveSigningIn = false) }
            AuthResult.Cancelled
        } catch (e: GetCredentialException) {
            Log.e(TAG, "Google Sign-In failed (${e.type})", e)
            val msg = e.localizedMessage ?: "Google Sign-In failed (${e.type})."
            _authUiState.update { it.copy(isInteractiveSigningIn = false, errorMessage = msg) }
            AuthResult.Error(msg)
        } catch (e: Exception) {
            Log.e(TAG, "Unexpected error during Google Sign-In", e)
            val msg = e.localizedMessage ?: "Unexpected sign-in error."
            _authUiState.update { it.copy(isInteractiveSigningIn = false, errorMessage = msg) }
            AuthResult.Error(msg)
        }
    }

    /**
     * Callback-based helper for interactive Google Sign-In button click.
     */
    fun onGoogleSignInClicked(
        context: Context,
        credentialManager: CredentialManager = CredentialManager.create(context),
        onAuthSuccess: () -> Unit,
        onAuthError: (String) -> Unit,
        scope: CoroutineScope,
        onAuthCancelled: () -> Unit = {}
    ) {
        scope.launch {
            when (val result = onGoogleSignInClicked(context, credentialManager)) {
                is AuthResult.Success -> onAuthSuccess()
                is AuthResult.Cancelled -> onAuthCancelled()
                is AuthResult.Error -> onAuthError(result.message)
            }
        }
    }

    internal suspend fun firebaseSignInWithCredential(
        credential: Credential,
        firebaseIdTokenExchanger: suspend (String) -> AuthResult = ::exchangeGoogleIdTokenWithFirebase
    ): AuthResult {
        if (credential is CustomCredential &&
            credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
        ) {
            return try {
                val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
                val idToken = googleIdTokenCredential.idToken
                if (idToken.isBlank()) {
                    AuthResult.Error("Google ID token was empty.")
                } else {
                    firebaseIdTokenExchanger(idToken)
                }
            } catch (e: Exception) {
                Log.e(TAG, "Failed to parse GoogleIdTokenCredential or sign in to Firebase", e)
                AuthResult.Error(e.localizedMessage ?: "Failed to verify Google ID token.")
            }
        }
        return AuthResult.Error("Unexpected credential type: ${credential.type}")
    }

    private suspend fun exchangeGoogleIdTokenWithFirebase(idToken: String): AuthResult {
        val firebaseCredential = GoogleAuthProvider.getCredential(idToken, null)
        val authResult = Firebase.auth.signInWithCredential(firebaseCredential).await()
        val user = authResult.user
        return if (user != null) {
            AuthResult.Success(user)
        } else {
            AuthResult.Error("Firebase Authentication did not return a user.")
        }
    }

    /**
     * Signs out of FirebaseAuth and clears Jetpack Credential Manager credential state
     * via [ClearCredentialStateRequest]. Local Room data is preserved so switching
     * or re-authenticating Google accounts can re-sync cleanly.
     */
    suspend fun signOut(
        context: Context,
        credentialManager: CredentialManager = CredentialManager.create(context)
    ) {
        try {
            Firebase.auth.signOut()
        } catch (e: Exception) {
            Log.w(TAG, "Error signing out of FirebaseAuth", e)
        }
        try {
            credentialManager.clearCredentialState(ClearCredentialStateRequest())
        } catch (e: ClearCredentialException) {
            Log.w(TAG, "Failed to clear CredentialManager state", e)
        } catch (e: Exception) {
            Log.w(TAG, "Unexpected error clearing credential state", e)
        } finally {
            _authUiState.update {
                AuthUiState(
                    currentUser = null,
                    isAutoSigningIn = false,
                    isInteractiveSigningIn = false,
                    errorMessage = null
                )
            }
        }
    }

    fun signOut(
        context: Context,
        credentialManager: CredentialManager = CredentialManager.create(context),
        onSignOutComplete: () -> Unit,
        scope: CoroutineScope
    ) {
        scope.launch {
            signOut(context, credentialManager)
            onSignOutComplete()
        }
    }
}
