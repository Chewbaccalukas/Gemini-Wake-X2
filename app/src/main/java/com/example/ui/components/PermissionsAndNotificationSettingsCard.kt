/**
 * Settings card for:
 * 1. Active window conversation model reply notifications (when backgrounded or screen off).
 * 2. Separate tap toggle buttons to Reset Permissions (in-app flags & rationale prompts)
 *    and Request Required Permissions (RECORD_AUDIO, POST_NOTIFICATIONS, CAMERA).
 */
@Composable
fun PermissionsAndNotificationSettingsCard(
    notifyActiveChatReplies: Boolean,
    onToggleNotifyActiveChatReplies: (Boolean) -> Unit,
    permissionsResetCount: Int,
    onResetPermissions: () -> Unit,
    onRequestRequiredPermissions: () -> Unit,
    modifier: Modifier = Modifier
) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .testTag("permissions_notifications_settings_card"),
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.45f)
        ),
        border = BorderStroke(
            1.dp,
            MaterialTheme.colorScheme.primary.copy(alpha = 0.35f)
        )
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            // Header
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Box(
                    modifier = Modifier
                        .size(42.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.primary.copy(alpha = 0.15f)),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = Icons.Default.NotificationsActive,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.primary,
                        modifier = Modifier.size(24.dp)
                    )
                }

                Spacer(modifier = Modifier.width(12.dp))

                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "Reply Notifications & Permissions",
                        style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = "Control active conversation reply alerts and manage app permission states.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }

            // 1. Model Replies in Active Window Conversation Notification Setting
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(12.dp))
                    .background(MaterialTheme.colorScheme.surface.copy(alpha = 0.7f))
                    .padding(horizontal = 12.dp, vertical = 10.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "Active Chat Model Reply Notifications",
                        style = MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.SemiBold),
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = "Notify when Gemini replies in the active chat while backgrounded or screen is off",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
                Spacer(modifier = Modifier.width(8.dp))
                Switch(
                    checked = notifyActiveChatReplies,
                    onCheckedChange = onToggleNotifyActiveChatReplies,
                    modifier = Modifier.testTag("notify_active_replies_switch")
                )
            }

            // 2. Separate Permission Tap Toggles: Reset Permissions & Ask for Required Permissions
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Text(
                        text = "App Permission Controls",
                        style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold),
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    if (permissionsResetCount > 0) {
                        Text(
                            text = "Reset $permissionsResetCount×",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.primary
                        )
                    }
                }

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    // Separate Button 1: Reset Permissions Tap Toggle
                    FilledTonalButton(
                        onClick = onResetPermissions,
                        modifier = Modifier
                            .weight(1f)
                            .testTag("reset_permissions_button")
                    ) {
                        Icon(
                            imageVector = Icons.Default.Refresh,
                            contentDescription = null,
                            modifier = Modifier.size(16.dp)
                        )
                        Spacer(modifier = Modifier.width(6.dp))
                        Text(
                            text = "Reset Perms",
                            style = MaterialTheme.typography.labelMedium
                        )
                    }

                    // Separate Button 2: Ask for Required Permissions Tap Toggle
                    Button(
                        onClick = onRequestRequiredPermissions,
                        modifier = Modifier
                            .weight(1f)
                            .testTag("request_permissions_button")
                    ) {
                        Icon(
                            imageVector = Icons.Default.Security,
                            contentDescription = null,
                            modifier = Modifier.size(16.dp)
                        )
                        Spacer(modifier = Modifier.width(6.dp))
                        Text(
                            text = "Ask Permissions",
                            style = MaterialTheme.typography.labelMedium
                        )
                    }
                }

                Text(
                    text = "Reset clears in-app permission flags & re-enables rationale prompts. Ask Permissions requests Microphone, Notifications, and Camera access.",
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.85f)
                )
            }
        }
    }
}
